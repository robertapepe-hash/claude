SELECT
  DATA,
  COUNT(*) AS linhas,
  ROUND(SUM(TGMV_MELI)/1e6, 1) AS tgmv_meli_mm,
  ROUND(SUM(GMV_SHOPEE)/1e6, 1) AS gmv_shopee_mm,
  ROUND(SUM(GMV_MERCADO)/1e6, 1) AS gmv_mercado_mm,
  MAX(UPDATE_DT) AS update_dt
FROM `meli-bi-data.SBOX_MKPBR.DM_MARKET_ASP_MONTHLY_VERTICAL_D1`
WHERE VERTICAL = 'HOME ELECTRONICS' AND DATA >= '2025-10-01'
GROUP BY 1
ORDER BY 1
