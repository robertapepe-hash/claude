SELECT
  VERTICAL,
  DOM_DOMAIN_AGG1,
  COUNT(*) AS linhas,
  MIN(DATA) AS min_data,
  MAX(DATA) AS max_data,
  ROUND(SUM(TGMV_MELI)/1e6, 1) AS tgmv_meli_mm,
  ROUND(SUM(GMV_SHOPEE)/1e6, 1) AS gmv_shopee_mm
FROM `meli-bi-data.SBOX_MKPBR.DM_MARKET_ASP_MONTHLY_VERTICAL_D1`
WHERE VERTICAL IN ('HOME ELECTRONICS','TECHNOLOGY')
GROUP BY 1, 2
ORDER BY 1, 2
