WITH base AS (
  SELECT
    CASE WHEN TIM_DAY BETWEEN DATE '2026-06-01' AND DATE '2026-06-07' THEN 'jun'
         WHEN TIM_DAY BETWEEN DATE '2026-05-01' AND DATE '2026-05-07' THEN 'mai' END AS periodo,
    DOM_AGG_2,
    KMI,
    VISITS_CHEAPER, VISITS_EQUAL, VISITS_MATCH
  FROM `meli-bi-data.WHOWNER.BT_COM_FAVORABILITY`
  WHERE (TIM_DAY BETWEEN DATE '2026-06-01' AND DATE '2026-06-07'
      OR TIM_DAY BETWEEN DATE '2026-05-01' AND DATE '2026-05-07')
    AND SIT_SITE_ID = 'MLB'
    AND FAVORABILITY_TYPE = 'BOX_ALL_ABC_PIX'
    AND DOM_AGG_1 = 'LARGE APPLIANCES'
    AND (FLG_BULKY IS NULL OR FLG_BULKY != 'true')
)
SELECT
  periodo,
  DOM_AGG_2,
  KMI,
  ROUND(SAFE_DIVIDE(SUM(VISITS_CHEAPER + VISITS_EQUAL), SUM(VISITS_MATCH)), 4) AS bpc_pix,
  SUM(VISITS_MATCH) AS visits_match
FROM base
WHERE periodo IS NOT NULL
GROUP BY GROUPING SETS ((periodo, DOM_AGG_2, KMI), (periodo, KMI), (periodo))
ORDER BY DOM_AGG_2, KMI, periodo
