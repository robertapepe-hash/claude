SELECT
TIM_DAY,
H.MELI_ID,
I.CUS_CUST_ID_SEL,
I.CUS_NICKNAME,
I.SELLER_REPUTATION,
CASE WHEN BEST_MELI_MIN_PRICE.MIN_PRICE >= BEST_RIVAL_MIN_PRICE.MIN_PRICE THEN 1 ELSE 0 END AS EXPENSIVE,
CASE WHEN I.ITE_ITEM_ID = BEST_MELI_MIN_PRICE.ITE_ITEM_ID THEN 1 ELSE 0 END AS GANHADOR_BB,
SUM(CASE WHEN MATCH_TYPE !='NO_MATCH' THEN H.VISITS_L30D END) MATCH_VISITS,
SUM(CASE WHEN MATCH_TYPE !='NO_MATCH' AND STATUS !='inactive' AND I.PRICE > 0 AND BEST_RIVAL_MIN_PRICE.MIN_PRICE > 0 and is_outlier = 'FALSE' AND I.PRICE >= 0.99 * BEST_RIVAL_MIN_PRICE.MIN_PRICE AND I.PRICE <= 1.01 * BEST_RIVAL_MIN_PRICE.MIN_PRICE THEN I.VISITS_L30D END) AS VISITS_MATCH,
SUM(CASE WHEN MATCH_TYPE !='NO_MATCH' AND STATUS !='inactive' AND I.PRICE > 0 AND BEST_RIVAL_MIN_PRICE.MIN_PRICE > 0 and is_outlier = 'FALSE' AND I.PRICE >1.01 * BEST_RIVAL_MIN_PRICE.MIN_PRICE THEN I.VISITS_L30D END) AS VISITS_EXPENSIVE,
SUM(CASE WHEN MATCH_TYPE !='NO_MATCH' AND STATUS !='inactive' AND I.PRICE > 0 AND BEST_RIVAL_MIN_PRICE.MIN_PRICE > 0 and is_outlier = 'FALSE' AND I.PRICE <0.99 * BEST_RIVAL_MIN_PRICE.MIN_PRICE THEN I.VISITS_L30D END) AS VISITS_CHEAPER,
FROM `meli-bi-data.WHOWNER.DM_COM_COMPETENCIA` H ,UNNEST(ITEMS) I
WHERE h.TIM_DAY >= DATE('__START__')
AND h.TIM_DAY <= DATE('__END__')
AND SIT_SITE_ID = 'MLB'
AND I.CUS_CUST_ID_SEL IN (__CUSTS__)
AND FLG_BULKY = TRUE
GROUP BY ALL
