WITH ids AS (SELECT s FROM UNNEST([1046986303,1917068106,1168726042,185297674,267892530,1737442603,1158756553,743518733,668432476,442421077,584911659,119612533,336971382,279642028,2441548732,234000251,85263796,1461582452,344811873,2323057123,323697852,447822366,167787623,1212138371,750553953,372535210,317390047,638325656,283059211,537315861]) AS s),
scope_items AS (
  SELECT DISTINCT ITE_ITEM_ID
  FROM `meli-bi-data.WHOWNER.DM_EFICIENCIA_MLB`
  WHERE ORD_CLOSED_DT BETWEEN DATE('2025-04-01') AND DATE('2026-05-31')
    AND CUS_CUST_ID_SEL IN (SELECT s FROM ids)
    AND VERTICAL='HOME ELECTRONICS' AND ITE_ITEM_HB_FLG=TRUE)
SELECT v.CUS_CUST_ID_SEL AS seller_id, v.TIM_DAY AS dia,
       SUM(v.QTY_VISITS) AS visitas, SUM(v.QTY_VISITS_VIP) AS visitas_vip
FROM `meli-bi-data.WHOWNER.BT_VISITS_MLB_UF` v
JOIN scope_items si ON v.ITE_ITEM_ID = si.ITE_ITEM_ID
WHERE v.TIM_DAY BETWEEN DATE('2025-04-01') AND DATE('2026-05-31')
  AND v.SIT_SITE_ID='MLB' AND v.CUS_CUST_ID_SEL IN (SELECT s FROM ids)
GROUP BY 1,2 ORDER BY 1,2
