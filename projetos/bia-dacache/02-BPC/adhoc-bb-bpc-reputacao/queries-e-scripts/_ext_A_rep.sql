WITH ids AS (SELECT s FROM UNNEST([1046986303,1917068106,1168726042,185297674,267892530,1737442603,1158756553,743518733,668432476,442421077,584911659,119612533,336971382,279642028,2441548732,234000251,85263796,1461582452,344811873,2323057123,323697852,447822366,167787623,1212138371,750553953,372535210,317390047,638325656,283059211,537315861]) AS s),
cal AS (SELECT day FROM UNNEST(GENERATE_DATE_ARRAY(DATE('2025-04-01'), DATE('2026-05-31'))) AS day),
log AS (
  SELECT CUS_CUST_ID_SEL sid, REP_CURRENT_LEVEL cur, REP_REAL_LEVEL real_lvl, REP_REPUTATION_FROM_DT fdt,
         DATE(REP_REPUTATION_FROM_DT) fd, DATE(IFNULL(REP_REPUTATION_UNTIL_DT, DATETIME('2999-01-01'))) ud
  FROM `meli-bi-data.WHOWNER.BT_REP_SELLER_REPUTATION_LOG`
  WHERE SIT_SITE_ID='MLB'
    AND DATE(REP_REPUTATION_FROM_DT) <= DATE('2026-05-31')
    AND DATE(IFNULL(REP_REPUTATION_UNTIL_DT, DATETIME('2999-01-01'))) >= DATE('2025-04-01')
    AND CUS_CUST_ID_SEL IN (SELECT s FROM ids))
SELECT sid AS seller_id, day,
       cur AS current_level,
       IFNULL(real_lvl, cur) AS real_level,
       CASE WHEN real_lvl IS NOT NULL AND real_lvl <> cur THEN 1 ELSE 0 END AS blindado
FROM cal JOIN log ON cal.day BETWEEN log.fd AND log.ud
QUALIFY ROW_NUMBER() OVER (PARTITION BY sid, day ORDER BY fdt DESC) = 1
ORDER BY seller_id, day
