SELECT
  ORD_CLOSED_DT AS DIA,
  CUS_CUST_ID_SEL,
  SUM(F_NMV_LC) AS NMV_LC,
  SUM(F_NSI) AS NSI,
  COUNT(DISTINCT ORD_ORDER_ID) AS PEDIDOS,
  COUNT(DISTINCT CUS_CUST_ID) AS COMPRADORES
FROM `meli-bi-data.WHOWNER.DM_EFICIENCIA_MLB`
WHERE ORD_CLOSED_DT >= DATE('__START__') AND ORD_CLOSED_DT <= DATE('__END__')
  AND CUS_CUST_ID_SEL IN (__CUSTS__)
  AND ITE_ITEM_HB_FLG = TRUE
GROUP BY 1, 2
